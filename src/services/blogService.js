export function obtenerPublicacionPorId(id) {
    const idNum = Number(id)
    if (!Number.isFinite(idNum)) return null
    return PUBLICACIONES.find((p) => p.id === idNum) || null
}

export function listarCategoriasBlog() {
    return [...new Set(PUBLICACIONES.map((p) => p.categoria))]
}
